CREATE SCHEMA IF NOT EXISTS sample;


-- r2dbc 테이블
CREATE TABLE sample.sample_r2dbc
(
    id   BIGSERIAL PRIMARY KEY,
    name VARCHAR(255),
    code VARCHAR(255)
);

CREATE TABLE sample.sample_input_r2dbc
(
    id          BIGSERIAL PRIMARY KEY,
    INPUT_NAME  VARCHAR(255),
    INPUT_VALUE VARCHAR(255),
    SAMPLE_ID   BIGINT,
    FOREIGN KEY (SAMPLE_ID) REFERENCES sample.sample_r2dbc (id) ON DELETE CASCADE ON UPDATE CASCADE
);



-- jpa 연관끊고, 테이블
CREATE TABLE sample.sample_no
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    code VARCHAR(255)
);

CREATE TABLE sample.sample_input_no
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    INPUT_NAME  VARCHAR(255),
    INPUT_VALUE VARCHAR(255),
    SAMPLE_ID   BIGINT,
    FOREIGN KEY (SAMPLE_ID) REFERENCES sample.sample_no (id) ON DELETE CASCADE ON UPDATE CASCADE
);
